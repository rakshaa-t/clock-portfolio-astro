function isVideo(src) {
  return /\.(mp4|webm|mov)(\?|$)/i.test(src || '');
}

function galleryFromImages(images = []) {
  return images
    .filter((src) => src && !isVideo(src))
    .map((src) => ({ type: 'image', src, caption: '' }));
}

